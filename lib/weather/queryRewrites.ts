/**
 * 用户输入 → 数据源认识的写法。
 *
 * 为什么需要这张表：
 * Open-Meteo 的地理编码数据来自 GeoNames，而 GeoNames 的中文别名质量很差——
 * 同一个字段里简体/繁体混用，还经常被加上行政后缀：
 *   东京 → 数据源里叫「東京」；伦敦 → 「倫敦」；纽约 → 「紐約市」；首尔 → 「首尔特别市」。
 * 而它的搜索是精确/近精确匹配，所以用简体名直接查：
 *   搜「纽约」一条都搜不到，搜「伦敦」只能搜到加拿大的伦敦，搜「东京」只能搜到江苏浙江的两个村。
 *
 * 怎么办（三种方案的取舍）：
 * 1. 内置简→繁字表：通用，但要塞几千字的映射，为几个城市名不值得。
 * 2. 改成英文查询：英文原名是 GeoNames 的主名称，召回最全，但结果会展示成英文，中文界面下体验倒退。
 * 3. **只收录「确实搜不到」的那些城市**，把用户输入改写成数据源认识的名字（本文件）。
 *    数据全部来自数据源本身（不编造译文），展示名仍然由数据源提供，因此列表与地点页永远不会不一致。
 *
 * 第三种的代价是需要维护一张手写表。为了让它可维护：
 * - 只收录真正搜不到的条目（当前 20 条，全部经过脚本验证）；
 * - 表里的目标名是数据源自己的名字，换了数据源就整表失效——但那本来也需要重写检索逻辑。
 */
const QUERY_REWRITES: [simplified: string, upstreamName: string][] = [
  ["东京", "東京"],
  ["大阪", "大阪市"],
  ["札幌", "札幌市"],
  ["首尔", "首尔特别市"],
  ["纽约", "紐約市"],
  ["西雅图", "西雅圖"],
  ["伦敦", "倫敦"],
  ["法兰克福", "法蘭克福"],
  ["罗马", "罗马市"],
  ["米兰", "Milan"],
  ["维也纳", "維也納"],
  ["奥克兰", "奧克蘭都會區"],
  ["温哥华", "溫哥華"],
  ["蒙特利尔", "Montréal"],
  ["马尼拉", "馬尼拉"],
  ["河内", "河內市"],
  ["台北", "台北市"],
  ["伊斯坦布尔", "伊斯坦堡"],
  ["开罗", "Cairo"],
  ["里斯本", "Lisbon"],
];

/**
 * 把用户输入改写成数据源认识的写法；没有对应条目时返回 null（表示原样查询即可）。
 *
 * 匹配规则放宽到「互相是前缀」：用户可能输入「纽约市」，也可能只输入「纽」，
 * 但太短的片段（如单个字）不作改写，否则「纽」会抢走纽卡斯尔等地的结果。
 */
export function rewriteQuery(input: string): string | null {
  const term = input.trim();
  if (term.length < 2) return null;

  for (const [simplified, upstreamName] of QUERY_REWRITES) {
    if (term === simplified || term.startsWith(simplified) || simplified.startsWith(term)) return upstreamName;
  }
  return null;
}
